-- 1) إضافة موظف
-- ----------------------------------------------------------------------------
-- أ) Authentication → Users → Add user
--    حط الإيميل وكلمة مرور قوية، وفعّل «Auto Confirm User».
-- ب) بدّل الإيميل والدور والاسم تحت ونفّذ:

insert into staff (user_id, role, name, active)
select id, 'executive', 'اسمك هنا', true
from auth.users
where email = 'ضع-إيميل-الموظف-هنا'
on conflict (user_id) do update
  set role = excluded.role, name = excluded.name, active = excluded.active;

-- الأدوار المتاحة:
--   'executive' — الإدارة التنفيذية: الأسعار، بوابة السعر (7)، الإعدادات،
